"""
Урок 6.2 "Индексы и срезы", шаг 9

Программа читает адрес почты и выводит часть после символа `@`. Если символа `@` нет, программа
должна вывести `Это не почта`. Сейчас на адресах без `@` выводится ерунда, исправьте программу.

Пример. Для `anna@mail.ru` программа выводит `mail.ru`, а для `anna.ru` выводит `Это не почта`.

Программа с ошибкой, которая лежит в редакторе на Stepik

    email = input()
    pos = email.find("@")
    print(email[pos + 1:])
"""

email = input()
pos = email.find("@")
if pos == -1:
    print("Это не почта")
else:
    print(email[pos + 1:])
