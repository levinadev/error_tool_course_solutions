"""
Урок 10.1 "Метод поиска ошибки", шаг 8

Программа читает целое число n и выводит сумму цифр. Ответ неверный, исправьте программу.

Пример. Для `2026` программа выводит `10`.

Программа с ошибкой, которая лежит в редакторе на Stepik

    n = int(input())
    total = 0
    while n > 0:
        total += n % 10
        n = n % 10
    print(total)
"""

n = int(input())
total = 0
while n > 0:
    total += n % 10
    n = n // 10
print(total)
