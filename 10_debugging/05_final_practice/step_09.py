"""
Урок 10.5 "Итоговая практика", шаг 9

Программа знает остатки товаров на складе. Она читает название товара и количество, которое хотят
купить. Если товара нет на складе, программа выводит `Нет такого товара`. Если товара не хватает,
выводит `Не хватает`. Иначе выводит, сколько товара останется. Исправьте программу.

Программа с ошибкой, которая лежит в редакторе на Stepik

    stock = {"ручка": 50, "тетрадь": 20, "ластик": 0}
    name = input()
    want = input()
    left = stock[name] - want
    if left < 0:
        print("Не хватает")
    else:
        print(left)
"""

stock = {"ручка": 50, "тетрадь": 20, "ластик": 0}
name = input()
want = int(input())
if name not in stock:
    print("Нет такого товара")
elif stock[name] < want:
    print("Не хватает")
else:
    print(stock[name] - want)
