"""
Урок 10.5 "Итоговая практика", шаг 2

Программа читает цену товара и количество (целые числа, каждое на своей строке). Если покупают от 10
штук включительно, на всю покупку скидка 20%. Программа выводит стоимость покупки. Исправьте
программу.

Пример. Для цены `100` и количества `10` программа выводит `800.0`, а для количества `2` выводит
`200`.

Программа с ошибкой, которая лежит в редакторе на Stepik

    price = input()
    count = int(input())
    total = price * count
    if count > 10
        total = total * 0.8
    print(total)
"""

price = int(input())
count = int(input())
total = price * count
if count >= 10:
    total = total * 0.8
print(total)
