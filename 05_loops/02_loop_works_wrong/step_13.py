"""
Урок 5.2 "Цикл работает, но не так", шаг 13

Программа читает целое число n и считает, сколько среди чисел от 1 до n делится на 3. Ответ
неверный, исправьте программу.

Пример. Для `10` таких чисел три, это 3, 6 и 9.

Программа с ошибкой, которая лежит в редакторе на Stepik

    n = int(input())
    count = 0
    for i in range(1, n + 1):
        if i % 3 == 0:
            count = 1
    print(count)
"""

n = int(input())
count = 0
for i in range(1, n + 1):
    if i % 3 == 0:
        count = count + 1
print(count)
