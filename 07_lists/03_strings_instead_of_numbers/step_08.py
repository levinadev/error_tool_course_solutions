"""
Урок 7.3 "Список из строк вместо списка чисел", шаг 8

Программа читает строку из целых чисел через пробел и выводит их по возрастанию через пробел. Ответ
иногда неверный, исправьте программу.

Пример. Для `10 2 33` программа выводит `2 10 33`.

Программа с ошибкой, которая лежит в редакторе на Stepik

    nums = input().split()
    nums.sort()
    print(" ".join(nums))
"""

nums = []
for x in input().split():
    nums.append(int(x))
nums.sort()
for x in nums:
    print(x, end=" ")
