"""
Урок 7.3 "Список из строк вместо списка чисел", шаг 7

Программа читает строку из целых чисел через пробел и выводит наибольшее. На некоторых данных ответ
неверный, исправьте программу.

Пример. Для `10 9 100` программа выводит `100`.

Программа с ошибкой, которая лежит в редакторе на Stepik

    nums = input().split()
    print(max(nums))
"""

nums = []
for x in input().split():
    nums.append(int(x))
print(max(nums))
