"""
Урок 7.3 "Список из строк вместо списка чисел", шаг 6

Программа читает строку из целых чисел через пробел и выводит их сумму. Программа падает, исправьте
её.

Пример. Для `3 9 4` программа выводит `16`.

Программа с ошибкой, которая лежит в редакторе на Stepik

    nums = input().split()
    print(sum(nums))
"""

nums = []
for x in input().split():
    nums.append(int(x))
print(sum(nums))
