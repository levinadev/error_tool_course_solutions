"""
Урок 7.1 "Методы, которые возвращают None", шаг 9

Программа читает строку с именами гостей через пробел, потом имя гостя, который не придёт. Она
убирает его из списка и выводит оставшихся через пробел. Если такого гостя нет в списке, список
выводится без изменений. Сейчас программа иногда падает, исправьте её.

Пример. Для гостей `Аня Борис Вера` и имени `Борис` программа выводит `Аня Вера`.

Программа с ошибкой, которая лежит в редакторе на Stepik

    guests = input().split()
    name = input()
    guests.remove(name)
    print(" ".join(guests))
"""

guests = input().split()
name = input()
if name in guests:
    guests.remove(name)
print(" ".join(guests))
